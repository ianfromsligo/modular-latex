def write_outputs(all_results, meta):
    payload = {
        "meta": meta,
        "results": {
            str(k): [{"N": int(N), "rho": float(rho), "delta": float(delta)}
                     for (N, rho, delta) in v]
            for k, v in all_results.items()
        },
    }
    OUT_JSON.write_text(json.dumps(payload, indent=2))

    lines = [
        "% Auto-generated by exp025c-v6-rebuild.py (v4)",
        "\\begin{tabular}{r r l l}", "\\toprule",
        "$k$ & $N$ & $\\rho$ & $\\delta/\\pi$ \\\\", "\\midrule",
    ]
    for k in sorted(all_results):
        for (N, rho, delta) in all_results[k]:
            lines.append(
                f"{k} & {N} & ${rho:.9f}$ & ${delta/math.pi:.4f}$ \\\\"
            )
    lines += ["\\bottomrule", "\\end{tabular}"]
    OUT_TEX.write_text("\n".join(lines))
    print(f"Wrote {OUT_JSON}")
    print(f"Wrote {OUT_TEX}")


