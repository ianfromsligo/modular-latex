def stage_3_validate(all_results):
    print()
    print("=" * 72)
    print("STAGE 3: validation against known revivals")
    print("=" * 72)
    ok = True
    for (k, rho, delta, N) in KNOWN_REVIVALS:
        hits = all_results.get(k, [])
        found = any(
            Nd == N and abs(rho_d - rho) < 1e-3
            and delta_distance(delta_d, delta) < 1e-6
            for (Nd, rho_d, delta_d) in hits
        )
        status = "PASS" if found else "FAIL"
        print(f"  {status}: k={k:2d}  rho={rho:.6f}  "
              f"delta={delta:.4f}  N={N:3d}")
        if not found:
            ok = False
    print("\n  All known revivals found." if ok
          else "\n  Some known revivals MISSED.")
    print()
    return ok


