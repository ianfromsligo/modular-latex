def stage_0_sanity():
    print("=" * 72)
    print("STAGE 0: physics engine sanity checks")
    print("=" * 72)
    ok = True
    for (k, rho, delta, N) in KNOWN_REVIVALS:
        U = construct_U_k(k, rho, delta)
        unit_diff = np.linalg.norm(U @ U.conj().T - np.eye(2 * k))
        if unit_diff > 1e-10:
            print(f"  FAIL: U_k not unitary for k={k} (diff={unit_diff:.2e})")
            ok = False
            continue
        passed, diff = verify_by_matrix_power(k, rho, delta, N)
        status = "PASS" if passed else "FAIL"
        print(f"  {status}: k={k:2d}  rho={rho:.6f}  "
              f"delta={delta:.4f}  N={N:3d}  ||U^N-I||={diff:.2e}")
        if not passed:
            ok = False
    print("\n  All known revivals verified. Physics engine OK." if ok
          else "\n  Some checks FAILED.")
    print()
    return ok


# ---------------------------------------------------------------------------
# Refinement: coarse minimize + fine local sweep
# ---------------------------------------------------------------------------

def refine_rho(k, rho_seed, delta, N, span=1e-8, n_local=400):
    """
    Coarse minimization followed by a fine local sweep. Reaches
    residuals around 1e-14 for genuine revivals.
    """
    def objective(rho):
        if rho <= 1e-12 or rho >= 1 - 1e-12:
            return 1e3
        eigs = eigenvalues_of(k, rho, delta)
        if eigs is None:
            return 1e3
        return residual_for_N(eigs, N)

    lo = max(1e-6, rho_seed - 0.05)
    hi = min(1 - 1e-6, rho_seed + 0.05)
    try:
        res = minimize_scalar(objective, bounds=(lo, hi), method="bounded",
                              options={"xatol": 1e-15})
        rho_coarse = float(res.x)
        best_res = float(res.fun)
        best_rho = rho_coarse
    except Exception:
        rho_coarse = rho_seed
        best_rho = rho_seed
        best_res = objective(rho_seed)

    fine_lo = max(1e-12, rho_coarse - span)
    fine_hi = min(1 - 1e-12, rho_coarse + span)
    rhos = np.linspace(fine_lo, fine_hi, n_local)
    for r in rhos:
        rv = objective(r)
        if rv < best_res:
            best_res = rv
            best_rho = float(r)

    return best_rho, best_res, n_local


# ---------------------------------------------------------------------------
# Stage 2 — search one k
# ---------------------------------------------------------------------------

def stage_2_search_k(k, verbose=True):
    raw = []
    family_keys = set()

    for i in range(1, RHO_STEPS):
        rho = i / RHO_STEPS
        for delta in DELTA_LIST:
            eigs = eigenvalues_of(k, rho, delta)
            if eigs is None:
                continue
            N, res = best_period(eigs)
            if N is None:
                continue

            key = (N, round(delta, 12))

            # Family check: collapse a continuous plateau to one entry.
            if key not in family_keys and detect_family(k, delta, N):
                family_keys.add(key)
                raw.append((N, 0.5, delta, 0.0, "family"))
                continue
            if key in family_keys:
                continue

            # Grid hit — verify and check isolation.
            if res < TOL_ACCEPT:
                passed, _ = verify_by_matrix_power(k, rho, delta, N)
                if passed and is_isolated(k, rho, delta, N):
                    raw.append((N, rho, delta, res, "grid"))
                continue

            # Near miss → refine
            if res < SEED_TOL:
                rho_ref, res_ref, _ = refine_rho(k, rho, delta, N)
                if res_ref < TOL_ACCEPT:
                    passed, _ = verify_by_matrix_power(k, rho_ref, delta, N)
                    if passed and is_isolated(k, rho_ref, delta, N):
                        raw.append((N, rho_ref, delta, res_ref, "refine"))

    # Deduplicate (delta modulo 2*pi)
    unique = []
    for entry in sorted(raw):
        N, rho, delta, _, _ = entry
        dup = False
        for (Nu, rhou, du) in unique:
            if (Nu == N and
                abs(rhou - rho) < DEDUP_RHO and
                delta_distance(du, delta) < DEDUP_DELTA):
                dup = True
                break
        if not dup:
            unique.append((N, rho, delta))

    if verbose:
        counts = {}
        for e in raw:
            counts[e[4]] = counts.get(e[4], 0) + 1
        detail = ", ".join(f"{c} {s}" for s, c in counts.items()) or "none"
        print(f"  k={k:2d}: {len(raw):5d} raw ({detail}) "
              f"→ {len(unique):3d} unique")

    return unique


