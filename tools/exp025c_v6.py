def stage_4_negative(all_results):
    print("=" * 72)
    print("STAGE 4: negative checks (should be empty)")
    print("=" * 72)
    ok = True
    for k in KNOWN_NON_REVIVALS_K:
        hits = all_results.get(k, [])
        if hits:
            print(f"  UNEXPECTED: k={k:2d} has {len(hits)} families:")
            for (N, rho, delta) in hits[:5]:
                print(f"      N={N} rho={rho:.9f} delta={delta/math.pi:.4f}pi")
            if len(hits) > 5:
                print(f"      ... and {len(hits) - 5} more")
            ok = False
        else:
            print(f"  PASS: k={k:2d} has no revival on the search grid")
    print()
    return ok


