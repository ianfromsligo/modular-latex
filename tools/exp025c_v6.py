# ---------------------------------------------------------------------------
# Physics engine
# ---------------------------------------------------------------------------

def construct_U_k(k, rho, delta):
    C = np.array(
        [
            [np.sqrt(rho),              np.sqrt(1 - rho) * np.exp(1j * delta)],
            [np.sqrt(1 - rho),         -np.sqrt(rho)     * np.exp(1j * delta)],
        ],
        dtype=complex,
    )
    S = np.zeros((2 * k, 2 * k), dtype=complex)
    for i in range(k):
        S[2 * ((i - 1) % k) + 0, 2 * i + 0] = 1.0
        S[2 * ((i + 1) % k) + 1, 2 * i + 1] = 1.0
    return S @ np.kron(np.eye(k), C)


def eigenvalues_of(k, rho, delta):
    try:
        U = construct_U_k(k, rho, delta)
        return np.linalg.eigvals(U)
    except Exception:
        return None


def residual_for_N(eigs, N):
    target = 2 * np.pi / N
    worst = 0.0
    for z in eigs:
        ang = np.angle(z)
        m = round(ang / target)
        dev = abs(ang - m * target)
        if dev > worst:
            worst = dev
    return worst


def best_period(eigs, n_max=N_MAX):
    best_res = float("inf")
    best_N = None
    for N in range(1, n_max + 1):
        r = residual_for_N(eigs, N)
        if r < best_res:
            best_res = r
            best_N = N
            if r < 1e-14:
                break
    return best_N, best_res


def verify_by_matrix_power(k, rho, delta, N, tol=TOL_ACCEPT):
    U = construct_U_k(k, rho, delta)
    Up = np.linalg.matrix_power(U, N)
    diff = np.linalg.norm(Up - np.eye(2 * k, dtype=complex))
    return diff < tol, diff


def delta_distance(a, b):
    d = abs(a - b) % (2 * math.pi)
    return min(d, 2 * math.pi - d)


# ---------------------------------------------------------------------------
# Isolation and family tests
# ---------------------------------------------------------------------------

def is_isolated(k, rho, delta, N, width=ISOLATION_WIDTH):
    """
    True if revival at (rho, delta, N) is NOT part of a continuous
    family. Uses the tight TOL_FAMILY so that only genuine revivals
    count as neighbours.
    """
    eps = width / 2
    for r in (rho - eps, rho + eps):
        if r <= 1e-6 or r >= 1 - 1e-6:
            continue
        eigs = eigenvalues_of(k, r, delta)
        if eigs is None:
            continue
        if residual_for_N(eigs, N) < TOL_FAMILY:
            return False
    return True


def detect_family(k, delta, N):
    """
    True if revival at (k, delta, N) is continuous over rho. Uses the
    tight TOL_FAMILY so spurious near-misses do not count as families.
    """
    samples = (0.2, 0.35, 0.5, 0.65, 0.8)
    for rho in samples:
        eigs = eigenvalues_of(k, rho, delta)
        if eigs is None:
            return False
        if residual_for_N(eigs, N) > TOL_FAMILY:
            return False
    return True


